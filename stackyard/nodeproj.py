"""Node.js projects (Express/Fastify/… backends, Vite frontends, monorepos with
backend/ and frontend/ folders) on DDEV.

`analyze()` looks at the project and builds a plan; `apply()` writes:
  - .ddev/config.stackyard.yaml: daemons for every service, exposed ports,
    a post-start hook that installs or rebuilds dependencies, system packages
    (e.g. Chromium for Puppeteer);
  - .ddev/vite.<service>.ddev.config.mjs: wraps the project's Vite config so it
    accepts the DDEV domain and hot reload works through HTTPS (the project's
    own config is never modified);
  - .env files created from .env.example with the DDEV URLs and generated
    secrets, plus .env.development.local for Vite frontends.

It also runs from the generated bash scripts:
    python3 -m stackyard.nodeproj detect <approot>        exit 0 if it is a Node project
    python3 -m stackyard.nodeproj flags <approot>         prints the `ddev config` flags
    python3 -m stackyard.nodeproj apply <approot> <name> <tld> [https|http]
"""

import json
import re
import secrets
import shutil
import sys
from pathlib import Path

SKIP_DIRS = {"node_modules", ".git", ".ddev", "vendor", "dist", "build", ".next", ".nuxt", "coverage", ".cache"}
SERVER_DEPS = ("express", "fastify", "koa", "hono", "@nestjs/core", "@hapi/hapi", "restify", "@adonisjs/core", "polka")
FRONTEND_DEPS = ("vite",)
DB_DEPS = {"mysql2": "mariadb:11.8", "mysql": "mariadb:11.8", "mariadb": "mariadb:11.8",
           "pg": "postgres:17", "postgres": "postgres:17"}
NATIVE_DEPS = ("bcrypt", "sqlite3", "better-sqlite3", "sharp", "canvas", "argon2", "node-sass", "bufferutil", "utf-8-validate")
PUPPETEER_DEPS = ("puppeteer", "puppeteer-core")
RESERVED_PORTS = {80, 443, 8025, 8026, 8036, 8037, 8142, 8143}
SECRET_NAME = re.compile(r"(SECRET|_SALT$|^SALT|SESSION_KEY|ENCRYPTION_KEY|SIGNING_KEY|COOKIE_KEY|APP_KEY)")
EXTERNAL_NAME = re.compile(r"(API_KEY|TOKEN|CLIENT_ID|CLIENT_SECRET|SITE_KEY|SECRET_KEY|DSN|WEBHOOK|PASSWORD|PRIVATE_KEY)")
PLACEHOLDER = re.compile(r"^$|^(your|change|replace|xxx|todo|example|<)|here$|_here|changeme", re.I)
LOCAL_URL = re.compile(r"https?://(?:localhost|127\.0\.0\.1|0\.0\.0\.0):(\d+)")

GENERATED_MARK = "# Generated by Stackyard"


# ===================================================================== analysis
def _read_json(path):
    try:
        return json.loads(Path(path).read_text())
    except (OSError, ValueError):
        return {}


def _deps(pkg):
    return {**pkg.get("dependencies", {}), **pkg.get("devDependencies", {})}


def _env_pairs(path):
    pairs = {}
    try:
        # utf-8-sig: files saved by some Windows editors start with a BOM
        for line in Path(path).read_text(encoding="utf-8-sig", errors="replace").splitlines():
            m = re.match(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$", line)
            if m:
                pairs[m.group(1)] = m.group(2).strip().strip("'\"")
    except OSError:
        pass
    return pairs


def _package_manager(folder, root):
    for d in (folder, root):
        if (d / "pnpm-lock.yaml").exists():
            return "pnpm"
        if (d / "yarn.lock").exists():
            return "yarn"
    return "npm"


def _server_port(folder, pkg):
    for name in (".env", ".env.example", ".env.local", ".env.development"):
        port = _env_pairs(folder / name).get("PORT")
        if port and port.isdigit():
            return int(port)
    # process.env.PORT || 3001 in the entry point or src/
    candidates = [folder / pkg.get("main", "index.js")] + sorted((folder / "src").glob("*.[jt]s"))[:20] + sorted(folder.glob("*.[jt]s"))[:10]
    for f in candidates:
        try:
            m = re.search(r"process\.env\.PORT\s*(?:\|\||\?\?)\s*['\"]?(\d{2,5})", f.read_text(errors="ignore"))
        except OSError:
            continue
        if m:
            return int(m.group(1))
    return 3000


def _vite_port(folder):
    for name in ("vite.config.js", "vite.config.mjs", "vite.config.ts", "vite.config.mts", "vite.config.cjs"):
        cfg = folder / name
        if cfg.exists():
            m = re.search(r"server\s*:\s*\{[^}]*?port\s*:\s*(\d{2,5})", cfg.read_text(errors="ignore"), re.S)
            return (int(m.group(1)) if m else 5173), name
    return 5173, None


def _node_major(folders):
    for folder in folders:
        nvmrc = folder / ".nvmrc"
        if nvmrc.exists():
            m = re.search(r"(\d+)", nvmrc.read_text())
            if m:
                return m.group(1)
        spec = str(_read_json(folder / "package.json").get("engines", {}).get("node", "")).strip()
        m = re.search(r"(\d+)", spec)
        # ">=18" is a minimum: the newest LTS satisfies it; "18.x", "^20", "~22" pin a major
        if m and not spec.startswith(">") and int(m.group(1)) >= 18:
            return m.group(1)
    return "24"


def _package_dirs(root):
    """The root plus first- and second-level folders with a package.json
    (e.g. backend/, frontend/, apps/web/)."""
    dirs = []
    if (root / "package.json").exists():
        dirs.append(root)
    for child in sorted(root.iterdir()):
        if not child.is_dir() or child.name in SKIP_DIRS or child.name.startswith("."):
            continue
        if (child / "package.json").exists():
            dirs.append(child)
        elif child.name in ("apps", "packages", "services"):
            dirs += [g for g in sorted(child.iterdir()) if g.is_dir() and (g / "package.json").exists()]
    return dirs


def is_node_project(root):
    root = Path(root)
    if (root / "composer.json").exists() or any(root.glob("*.php")) or (root / "artisan").exists():
        return False
    return any(_classify(d, root) for d in _package_dirs(root))


def _classify(folder, root):
    pkg = _read_json(folder / "package.json")
    deps = _deps(pkg)
    scripts = pkg.get("scripts", {})
    if any(d in deps for d in FRONTEND_DEPS):
        return "vite"
    if any(d in deps for d in SERVER_DEPS):
        return "server"
    # an orchestrating root ("cd backend && …", concurrently) is not a service
    if folder == root and any("cd " in v or "concurrently" in v for v in scripts.values()):
        return None
    if "dev" in scripts or "start" in scripts:
        return "server"
    return None


def analyze(root, scheme="https"):
    """Returns the plan dict, or None when this is not a Node project.
    scheme: 'https' or 'http', the protocol the project is served with."""
    root = Path(root)
    if not is_node_project(root):
        return None
    services, deps_all, used = [], {}, set()
    folders = _package_dirs(root)
    for folder in folders:
        kind = _classify(folder, root)
        if not kind:
            continue
        pkg = _read_json(folder / "package.json")
        deps = _deps(pkg)
        deps_all.update(deps)
        rel = "." if folder == root else str(folder.relative_to(root))
        name = re.sub(r"[^a-z0-9-]+", "-", (folder.name if folder != root else ("frontend" if kind == "vite" else "app")).lower()).strip("-") or "app"
        while name in used:
            name += "-2"
        used.add(name)
        pm = _package_manager(folder, root)
        native = [d for d in NATIVE_DEPS if d in deps]
        if kind == "vite":
            port, config = _vite_port(folder)
            services.append({"name": name, "dir": rel, "kind": kind, "port": port, "vite_config": config, "pm": pm, "native": native})
        else:
            scripts = pkg.get("scripts", {})
            script = "dev" if "dev" in scripts else ("start" if "start" in scripts else None)
            command = f"{pm} run {script}" if script else f"node {pkg.get('main', 'index.js')}"
            services.append({"name": name, "dir": rel, "kind": kind, "port": _server_port(folder, pkg), "command": command, "pm": pm, "native": native})
    if not services:
        return None

    # the frontend (or the only service) gets the main URL on 80/443
    primary = next((s for s in services if s["kind"] == "vite"), services[0])
    taken = set(RESERVED_PORTS)
    for s in services:
        s["primary"] = s is primary
        if s["primary"]:
            s["https_port"], s["http_port"] = 443, 80
        else:
            port = s["port"]
            while port in taken or port + 1 in taken:
                port += 10
            # the chosen scheme keeps the service's own port (e.g. 3001); the other one gets port+1
            s["https_port"], s["http_port"] = (port, port + 1) if scheme == "https" else (port + 1, port)
            taken |= {port, port + 1}
        s["public_port"] = s["https_port"] if scheme == "https" else s["http_port"]

    db = next((v for k, v in DB_DEPS.items() if k in deps_all), None)
    return {
        "root": str(root),
        "scheme": scheme,
        "services": services,
        "node": _node_major([root] + [root / s["dir"] for s in services]),
        "database": db,
        "puppeteer": any(d in deps_all for d in PUPPETEER_DEPS),
        "native": sorted(d for d in NATIVE_DEPS if d in deps_all),
        "yarn_or_pnpm": any(s["pm"] != "npm" for s in services),
    }


def ddev_config_flags(plan):
    """Flags for `ddev config` (type, web server, database, Node version)."""
    flags = ["--project-type=generic", "--webserver-type=generic", "--docroot=", f"--nodejs-version={plan['node']}"]
    if plan["database"]:
        flags.append(f"--database={plan['database']}")
    else:
        flags.append("--omit-containers=db")
    if plan["yarn_or_pnpm"]:
        flags.append("--corepack-enable")
    return " ".join(flags)


# ===================================================================== files
def _url(name, tld, port, scheme="https"):
    default = 443 if scheme == "https" else 80
    return f"{scheme}://{name}.{tld}" + ("" if port == default else f":{port}")


def _yaml_str(value):
    return json.dumps(value)  # JSON strings are valid YAML strings


def svc_url(name, tld, service, scheme="https"):
    return _url(name, tld, service["public_port"], scheme)


def ddev_yaml(plan):
    lines = [GENERATED_MARK + " for this Node project. It is merged with config.yaml.",
             "# Edit it freely, or let Stackyard regenerate it (Tools → Set up for Node).", ""]
    if plan["puppeteer"]:
        lines += ["webimage_extra_packages: [chromium, fonts-noto-color-emoji]",
                  "web_environment:", "  - PUPPETEER_SKIP_DOWNLOAD=true", "  - PUPPETEER_EXECUTABLE_PATH=/usr/bin/chromium", ""]
    lines.append("web_extra_daemons:")
    for s in plan["services"]:
        workdir = "/var/www/html" + ("" if s["dir"] == "." else f"/{s['dir']}")
        if s["kind"] == "vite":
            cmd = f"npx vite --config /var/www/html/.ddev/vite.{s['name']}.ddev.config.mjs --port {s['port']} --strictPort"
        else:
            cmd = s["command"]
        lines += [f"  - name: {s['name']}", f"    command: {_yaml_str(cmd)}", f"    directory: {workdir}"]
    lines += ["", "web_extra_exposed_ports:"]
    # the primary service goes first: DDEV uses the first exposed port as the project URL
    for s in sorted(plan["services"], key=lambda svc: not svc["primary"]):
        lines += [f"  - name: {s['name']}", f"    container_port: {s['port']}",
                  f"    http_port: {s['http_port']}", f"    https_port: {s['https_port']}"]
    lines += ["", "hooks:", "  post-start:", "    - exec: \"bash /var/www/html/.ddev/stackyard-node-prepare.sh\"", ""]
    return "\n".join(lines)


def prepare_script(plan):
    """Runs in the web container after start: installs dependencies that are
    missing, rebuilds native modules that were built on another system (e.g.
    node_modules copied from Windows), then restarts the daemons."""
    out = ["#!/bin/bash", GENERATED_MARK + ": prepares the Node dependencies in the container.",
           "# --force reinstalls the dependencies of every service.", "set -u", "changed=0", 'force="${1:-}"']
    seen = set()
    for s in plan["services"]:
        if s["dir"] in seen:
            continue
        seen.add(s["dir"])
        d = "/var/www/html" + ("" if s["dir"] == "." else f"/{s['dir']}")
        pm = s["pm"]
        install = {"npm": "npm install --no-audit --no-fund", "yarn": "yarn install", "pnpm": "pnpm install"}[pm]
        rebuild = {"npm": "npm rebuild", "yarn": "npm rebuild", "pnpm": "pnpm rebuild"}[pm]
        out += [
            f"cd {d} || exit 0",
            "marker=node_modules/.stackyard-linux",
            "if [ ! -d node_modules ] || [ \"$force\" = --force ]; then",
            f"  echo 'Stackyard: installing dependencies in {s['dir']}'; {install} && touch \"$marker\"; changed=1",
            "elif [ ! -f \"$marker\" ]; then",
            f"  echo 'Stackyard: rebuilding native modules in {s['dir']} for Linux'; {rebuild} && touch \"$marker\"; changed=1",
            "elif [ package.json -nt \"$marker\" ]; then",
            f"  echo 'Stackyard: package.json changed in {s['dir']}, updating'; {install} && touch \"$marker\"; changed=1",
            "fi",
        ]
        # npm 11 skips install scripts not listed in allowScripts: make sure every native module loads
        for mod in s.get("native", []):
            out.append(f"node -e \"require('{mod}')\" >/dev/null 2>&1 || "
                       f"{{ echo 'Stackyard: building native module {mod}'; npm rebuild {mod} >/dev/null 2>&1; changed=1; }}")
    out += ["if [ \"$changed\" = 1 ]; then sudo supervisorctl restart 'webextradaemons:*' >/dev/null 2>&1 || true; fi", ""]
    return "\n".join(out)


def vite_wrapper(service, plan, tld):
    # the wrapper lives in .ddev/, so the project's config is one level up
    rel_config = "../" + ("" if service["dir"] == "." else service["dir"] + "/") + service["vite_config"]
    return f"""// Generated by Stackyard: runs the project's Vite config through DDEV without modifying it.
import base from '{rel_config}'

export default async (env) => {{
  const config = (typeof base === 'function' ? await base(env) : await base) || {{}}
  return {{
    ...config,
    server: {{
      ...(config.server || {{}}),
      host: '0.0.0.0',
      port: {service['port']},
      strictPort: true,
      allowedHosts: ['.{tld}', 'localhost'],
      hmr: {{ protocol: '{"wss" if plan["scheme"] == "https" else "ws"}', host: process.env.DDEV_HOSTNAME, clientPort: {service['public_port']} }},
    }},
  }}
}}
"""


def _random_secret():
    return secrets.token_hex(32)


def _env_names_in_code(folder):
    names = set()
    exts = {".js", ".mjs", ".cjs", ".ts", ".mts", ".cts"}
    src_files = []
    for sub in ("src", "server", "app", "lib", "config"):
        base = folder / sub
        if base.is_dir():
            src_files += [p for p in base.rglob("*") if p.suffix in exts and "node_modules" not in p.parts][:400]
    src_files += [p for p in folder.glob("*") if p.suffix in exts]
    for f in src_files[:600]:
        try:
            names |= set(re.findall(r"process\.env\.([A-Z][A-Z0-9_]+)", f.read_text(errors="ignore")))
        except OSError:
            pass
    return names


def setup_env(plan, name, tld):
    """Creates/updates .env files. Returns (notes, missing) for the report."""
    root = Path(plan["root"])
    notes, missing = [], []
    scheme = plan["scheme"]
    port_urls = {s["port"]: _url(name, tld, s["public_port"], scheme) for s in plan["services"]}
    # URLs this project already points to (previous run, maybe with the other scheme)
    own_url = re.compile(rf"https?://{re.escape(name)}\.{re.escape(tld)}(?::(\d+))?")

    def to_scheme(match):
        port = int(match.group(1)) if match.group(1) else None
        if port in (None, 80, 443):
            return _url(name, tld, 443 if scheme == "https" else 80, scheme)
        # 3001 <-> 3002 style pairs: map back to the service and use its public port
        for svc in plan["services"]:
            if port in (svc["https_port"], svc["http_port"]):
                return _url(name, tld, svc["public_port"], scheme)
        return match.group(0)
    for s in plan["services"]:
        folder = root / s["dir"]
        if s["kind"] == "vite":
            # Vite reads VITE_* at build time: point local URLs to DDEV in .env.development.local
            local = folder / ".env.development.local"
            if local.exists() and not local.read_text().startswith("# Generated by Stackyard"):
                continue  # the user's own file: leave it alone
            values = {}
            for src in (".env.development", ".env", ".env.example"):
                for k, v in _env_pairs(folder / src).items():
                    m = LOCAL_URL.search(v)
                    if k.startswith("VITE_") and m and int(m.group(1)) in port_urls and k not in values:
                        values[k] = LOCAL_URL.sub(lambda mm: port_urls.get(int(mm.group(1)), mm.group(0)), v)
            if values:
                local.write_text("# Generated by Stackyard: DDEV URLs for local development\n" +
                                 "".join(f"{k}={v}\n" for k, v in values.items()))
                notes.append(f"{s['dir']}/.env.development.local")
            continue

        env = folder / ".env"
        example = next((folder / n for n in (".env.example", ".env.sample", ".env.dist") if (folder / n).exists()), None)
        if not env.exists():
            if not example:
                continue
            shutil.copy2(example, env)
            notes.append(f"{s['dir']}/.env ← {example.name}")
        text = env.read_text(encoding="utf-8-sig", errors="replace")
        pairs = _env_pairs(env)
        changed = False
        # local URLs -> DDEV URLs (BASE_URL, FRONTEND_URL, CORS_ORIGIN…), except the service's own PORT
        def fix(match):
            port = int(match.group(1))
            return port_urls.get(port, match.group(0))
        for key, value in pairs.items():
            if key != "PORT" and (LOCAL_URL.search(value) or own_url.search(value)):
                new = own_url.sub(to_scheme, LOCAL_URL.sub(fix, value))
                if new != value:
                    text = re.sub(rf"^(\s*(?:export\s+)?{key}\s*=\s*).*$", lambda m, n=new: m.group(1) + n, text, count=1, flags=re.M)
                    changed = True
        # secrets: generate the ones the app can create itself
        wanted = (set(pairs) | _env_names_in_code(folder))
        for key in sorted(wanted):
            value = pairs.get(key)
            if SECRET_NAME.search(key) and not EXTERNAL_NAME.search(key) and (value is None or PLACEHOLDER.search(value)):
                secret = _random_secret()
                if value is None:
                    text = text.rstrip("\n") + f"\n{key}={secret}\n"
                else:
                    text = re.sub(rf"^(\s*(?:export\s+)?{key}\s*=\s*).*$", lambda m, n=secret: m.group(1) + n, text, count=1, flags=re.M)
                notes.append(f"{s['dir']}/.env: {key} generated")
                changed = True
            elif key in pairs and EXTERNAL_NAME.search(key) and PLACEHOLDER.search(value or ""):
                missing.append(f"{s['dir']}/.env: {key}")
        if changed:
            env.write_text(text)
    return notes, missing


def apply(plan, name, tld):
    """Writes every file. Returns a human-readable report (list of lines)."""
    root = Path(plan["root"])
    ddev_dir = root / ".ddev"
    ddev_dir.mkdir(exist_ok=True)
    (ddev_dir / "config.stackyard.yaml").write_text(ddev_yaml(plan))
    prep = ddev_dir / "stackyard-node-prepare.sh"
    prep.write_text(prepare_script(plan))
    prep.chmod(0o755)
    for s in plan["services"]:
        if s["kind"] == "vite" and s.get("vite_config"):
            (ddev_dir / f"vite.{s['name']}.ddev.config.mjs").write_text(vite_wrapper(s, plan, tld))
    notes, missing = setup_env(plan, name, tld)

    report = ["Services:"]
    for s in plan["services"]:
        report.append(f"  {s['name']:<10} {s['kind']:<7} {s['dir']:<12} → {_url(name, tld, s['public_port'], plan['scheme'])}")
    report.append(f"Node {plan['node']} · database: {plan['database'] or 'none'}"
                  + (" · Chromium for Puppeteer" if plan["puppeteer"] else "")
                  + (f" · native modules: {', '.join(plan['native'])}" if plan["native"] else ""))
    if notes:
        report.append("Environment files:")
        report += [f"  {n}" for n in notes]
    if missing:
        report.append("Fill these with real values (the app needs them for some features):")
        report += [f"  {m}" for m in missing]
    return report


def main(argv):
    usage = "usage: python3 -m stackyard.nodeproj detect|flags <approot> | apply <approot> <name> <tld> [https|http]"
    if len(argv) < 3 or argv[1] not in ("detect", "flags", "apply") or (argv[1] == "apply" and len(argv) not in (5, 6)):
        print(usage, file=sys.stderr)
        return 2
    command, root = argv[1], argv[2]
    scheme = argv[5] if len(argv) == 6 and argv[5] in ("http", "https") else "https"
    plan = analyze(root, scheme)
    if command == "detect":
        return 0 if plan else 1
    if not plan:
        print("Not a Node project.", file=sys.stderr)
        return 1
    if command == "flags":
        print(ddev_config_flags(plan))
        return 0
    for line in apply(plan, argv[3], argv[4]):
        print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
